// PostgreSQL schema and query helpers. The database is either
//   a PostgreSQL server - a postgres:// or postgresql:// URL (DATABASE_URL), through the `pg` driver, or
//   PGlite            - real PostgreSQL compiled to WebAssembly, running inside Node. A data directory,
//                       or 'memory' for a throwaway database. Local runs and tests use it, so no server is needed.
// Queries use ? placeholders, which are numbered ($1, $2, ...) before they are sent.
