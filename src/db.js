const pad = (n) => String(n).padStart(2, '0');

// The moment, for TIMESTAMPTZ columns. Stored in UTC; pages show it in India time.
export const now = (d = new Date()) => d.toISOString();

// The calendar date in India (YYYY-MM-DD), whatever the server's own time zone. Return windows,
// delivery promises and the assistant's daily limit count India days.
const INDIA_DAY = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Kolkata', year: 'numeric', month: '2-digit', day: '2-digit' });
export const indiaDate = (d = new Date()) => INDIA_DAY.format(d);
export const isoDate = indiaDate;

// A YYYY-MM-DD date plus a number of days.
export function addDays(day, n) {
  const d = new Date(`${day}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

export const TABLES = [...SCHEMA.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((m) => m[1]);
const TABLES_WITHOUT_ID = new Set(['sessions', 'inventory', 'cart_items', 'assistant_usage', 'idempotency_keys']);

// ? placeholders become $1, $2, ... and LIKE becomes ILIKE, so searches ignore case.
export function toPostgres(sql) {
  let n = 0;
  let quoted = false;
  let out = '';
  for (const ch of sql) {
    if (ch === "'") quoted = !quoted;
    out += ch === '?' && !quoted ? `$${++n}` : ch;
  }
  return out.replace(/\bLIKE\b/g, 'ILIKE');
}

// undefined can't be bound.
const bind = (params) => params.map((p) => (p === undefined ? null : p));

// COUNT and SUM return int8/numeric, which drivers hand back as strings. Read them as JS numbers.
const NUMBER_TYPES = [20, 1700];
// DATE comes back as the plain YYYY-MM-DD text, not a JS Date at some server's midnight.
const DATE_TYPE = 1082;
const keep = (v) => v;

// pool: anything with query(text, params) -> {rows} and connect() -> client {query, release}.
class PostgresDb {
  #pool;
  #tx = new AsyncLocalStorage();

  constructor(pool) {
    this.#pool = pool;
  }

  #target() {
    return this.#tx.getStore() || this.#pool;
  }

  async query(sql, params = []) {
    return (await this.#target().query(toPostgres(sql), bind(params))).rows;
  }

  // Returns the new row's id for INSERTs into tables that have one.
  async run(sql, params = []) {
    const m = /^\s*INSERT INTO (\w+)/i.exec(sql);
    if (!m || TABLES_WITHOUT_ID.has(m[1])) {
      await this.query(sql, params);
      return 0;
    }
    return Number((await this.query(`${sql} RETURNING id`, params))[0].id);
  }

  // The number of rows an UPDATE or DELETE changed.
  async changes(sql, params = []) {
    const r = await this.#target().query(toPostgres(sql), bind(params));
    return r.rowCount ?? r.affectedRows ?? 0;
  }

  async exec(sql) {
    await this.#target().query(sql);
  }

  // Everything inside fn, including helpers called with the outer db, runs on
  // the transaction's own connection. Nested calls join the outer transaction.
  async transaction(fn) {
    if (this.#tx.getStore()) return fn();
    const client = await this.#pool.connect();
    try {
      // No global lock: transactions run side by side. Code that reads and then writes the
      // same rows locks just those rows (SELECT ... FOR UPDATE, or a guarded UPDATE; see
      // orders.js), and the few jobs that must run alone take a named lock (lockNamed).
      await client.query('BEGIN');
      const result = await this.#tx.run(client, fn);
      await client.query('COMMIT');
      return result;
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {});
      throw e;
    } finally {
      client.release();
    }
  }

  close() {
    return this.#pool.end();
  }
}

// PGlite is a single in-process connection. connect() hands it out to one
// transaction at a time; plain queries outside a transaction go straight to it.
function pglitePool(pg) {
  let queue = Promise.resolve();
  const query = (text, params) => (params ? pg.query(text, params) : pg.exec(text).then((rs) => rs.at(-1) || { rows: [] }));
  return {
    query,
    async connect() {
      const previous = queue;
      let release;
      queue = new Promise((resolve) => { release = resolve; });
      await previous;
      return { query, release };
    },
    end: () => pg.close(),
  };
}

export const isServerUrl = (target) => /^postgres(ql)?:\/\//.test(String(target || ''));

// target: a postgres:// URL, a PGlite data directory, or 'memory'.
export async function connect(target = 'memory', options = {}) {
  if (isServerUrl(target)) {
    const { default: pg } = await import('pg');
    const getTypeParser = (oid, format) => (NUMBER_TYPES.includes(oid) ? Number : oid === DATE_TYPE ? keep : pg.types.getTypeParser(oid, format));
    return new PostgresDb(new pg.Pool({ connectionString: target, max: options.maxConnections || 5, types: { getTypeParser } }));
  }
  const { PGlite } = await import('@electric-sql/pglite');
  const { pg_trgm } = await import('@electric-sql/pglite/contrib/pg_trgm'); // typo matching in search
  const parsers = { ...Object.fromEntries(NUMBER_TYPES.map((oid) => [oid, Number])), [DATE_TYPE]: keep };
  // One options object: PGlite.create(undefined, options) silently ignores the options.
  const dataDir = target === 'memory' ? undefined : target;
  return new PostgresDb(pglitePool(await PGlite.create({ dataDir, parsers, extensions: { pg_trgm } })));
}

export function initSchema(db) {
  return db.exec(SCHEMA);
}

// Drop Equidron's own tables (used by --reset). Other tables in the database are left alone.
export async function dropSchema(db) {
  for (const table of [...TABLES].reverse()) {
    await db.exec(`DROP TABLE IF EXISTS ${table} CASCADE`);
  }
}

export const all = (db, sql, ...params) => db.query(sql, params);

export async function one(db, sql, ...params) {
  return (await db.query(sql, params))[0] ?? null;
}

export async function scalar(db, sql, ...params) {
  const r = await one(db, sql, ...params);
  return r ? Object.values(r)[0] : null;
}

export const run = (db, sql, ...params) => db.run(sql, params);

// For guarded updates: UPDATE ... WHERE <still true>, then check that a row changed.
export const changes = (db, sql, ...params) => db.changes(sql, params);

// Named locks for the few jobs that must never run twice at once. Held until the
// transaction ends. Everything else locks only the rows it changes.
export const LOCKS = { seed: 7426002, settlement: 7426003 };
export async function lockNamed(db, name) {
  await db.query('SELECT pg_advisory_xact_lock(?) AS locked', [LOCKS[name]]);
}

// Run fn in a transaction, rolling back if it throws.
export const transaction = (db, fn) => db.transaction(fn);

// JSONB columns already arrive as objects; older text values are parsed.
export function loads(value, fallback = null) {
  if (value == null) return fallback;
  if (typeof value !== 'string') return value;
  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}

export const dumps = (v) => JSON.stringify(v);
