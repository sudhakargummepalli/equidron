const pad = (n) => String(n).padStart(2, '0');

export function now(d = new Date()) {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}

export function isoDate(d) {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

export const TABLES = [...SCHEMA.matchAll(/CREATE TABLE IF NOT EXISTS (\w+)/g)].map((m) => m[1]);
const TABLES_WITHOUT_ID = new Set(['sessions', 'inventory', 'cart_items']);

// ? placeholders become $1, $2, ... and LIKE becomes ILIKE, so searches ignore case.
export function toPostgres(sql) {
  let n = 0;
  let quoted = false;
  let out = '';
  for (const ch of sql) {
    if (ch === "'") quoted = !quoted;
    out += ch === '?' && !quoted ? `$${++n}` : ch;
  }
  return out.replace(/\bLIKE\b/g, 'ILIKE');
}

// undefined can't be bound, and flag columns are integers. Normalise both.
const bind = (params) => params.map((p) => (p === undefined ? null : typeof p === 'boolean' ? (p ? 1 : 0) : p));

// COUNT and SUM return int8/numeric, which drivers hand back as strings. Read them as JS numbers.
const NUMBER_TYPES = [20, 1700];

// pool: anything with query(text, params) -> {rows} and connect() -> client {query, release}.
class PostgresDb {
  #pool;
  #tx = new AsyncLocalStorage();

  constructor(pool) {
    this.#pool = pool;
  }

  #target() {
    return this.#tx.getStore() || this.#pool;
  }

  async query(sql, params = []) {
    return (await this.#target().query(toPostgres(sql), bind(params))).rows;
  }

  // Returns the new row's id for INSERTs into tables that have one.
  async run(sql, params = []) {
    const m = /^\s*INSERT INTO (\w+)/i.exec(sql);
    if (!m || TABLES_WITHOUT_ID.has(m[1])) {
      await this.query(sql, params);
      return 0;
    }
    return Number((await this.query(`${sql} RETURNING id`, params))[0].id);
  }

  async exec(sql) {
    await this.#target().query(sql);
  }

  // Everything inside fn, including helpers called with the outer db, runs on
  // the transaction's own connection. Nested calls join the outer transaction.
  async transaction(fn) {
    if (this.#tx.getStore()) return fn();
    const client = await this.#pool.connect();
    try {
      await client.query('BEGIN');
      // One writer at a time: checkout reads stock and then reserves it, and nothing may slip in between.
      await client.query('SELECT pg_advisory_xact_lock(7426001)');
      const result = await this.#tx.run(client, fn);
      await client.query('COMMIT');
      return result;
    } catch (e) {
      await client.query('ROLLBACK').catch(() => {});
      throw e;
    } finally {
      client.release();
    }
  }

  close() {
    return this.#pool.end();
  }
}

// PGlite is a single in-process connection. connect() hands it out to one
// transaction at a time; plain queries outside a transaction go straight to it.
function pglitePool(pg) {
  let queue = Promise.resolve();
  const query = (text, params) => (params ? pg.query(text, params) : pg.exec(text).then((rs) => rs.at(-1) || { rows: [] }));
  return {
    query,
    async connect() {
      const previous = queue;
      let release;
      queue = new Promise((resolve) => { release = resolve; });
      await previous;
      return { query, release };
    },
    end: () => pg.close(),
  };
}

export const isServerUrl = (target) => /^postgres(ql)?:\/\//.test(String(target || ''));

// target: a postgres:// URL, a PGlite data directory, or 'memory'.
export async function connect(target = 'memory', options = {}) {
  if (isServerUrl(target)) {
    const { default: pg } = await import('pg');
    const getTypeParser = (oid, format) => (NUMBER_TYPES.includes(oid) ? Number : pg.types.getTypeParser(oid, format));
    return new PostgresDb(new pg.Pool({ connectionString: target, max: options.maxConnections || 5, types: { getTypeParser } }));
  }
  const { PGlite } = await import('@electric-sql/pglite');
  const parsers = Object.fromEntries(NUMBER_TYPES.map((oid) => [oid, Number]));
  return new PostgresDb(pglitePool(await PGlite.create(target === 'memory' ? undefined : target, { parsers })));
}

export function initSchema(db) {
  return db.exec(SCHEMA);
}

// Drop Equidron's own tables (used by --reset). Other tables in the database are left alone.
export async function dropSchema(db) {
  for (const table of [...TABLES].reverse()) {
    await db.exec(`DROP TABLE IF EXISTS ${table} CASCADE`);
  }
}

export const all = (db, sql, ...params) => db.query(sql, params);

export async function one(db, sql, ...params) {
  return (await db.query(sql, params))[0] ?? null;
}

export async function scalar(db, sql, ...params) {
  const r = await one(db, sql, ...params);
  return r ? Object.values(r)[0] : null;
}

export const run = (db, sql, ...params) => db.run(sql, params);

// Run fn in a transaction, rolling back if it throws.
export const transaction = (db, fn) => db.transaction(fn);

export function loads(value, fallback = null) {
  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}

export const dumps = (v) => JSON.stringify(v);
