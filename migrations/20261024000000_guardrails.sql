-- Guardrails: every refusal or flag raised by src/guardrails.js is recorded here, so a person
-- can see what the rules stopped, why, and for which role. Nothing is deleted from it.
CREATE TABLE IF NOT EXISTS guardrail_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role TEXT NOT NULL CHECK (role IN ('customer', 'seller', 'ops', 'agent', 'system')),
    area TEXT NOT NULL,
    rule TEXT NOT NULL,
    severity TEXT NOT NULL CHECK (severity IN ('flag', 'refuse')),
    actor_id TEXT,
    detail JSONB,
    at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS guardrail_events_recent ON guardrail_events (at DESC);
