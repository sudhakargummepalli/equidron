-- Phase 6: a proposal is a change the assistant suggests and the customer confirms in the chat.
-- The agent never cancels an order or opens a return itself: it writes a proposal, the tap on the
-- card calls the normal API, and the customer is the one who decided.
CREATE TABLE IF NOT EXISTS proposals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    kind TEXT NOT NULL CHECK (kind IN ('cancel_order', 'return_item')),
    payload JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'dismissed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS proposals_open ON proposals (user_id, status) WHERE status = 'pending';
