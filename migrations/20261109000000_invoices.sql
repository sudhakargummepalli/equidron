-- Phase 10: the GST invoice for an order. Prices in the store are tax-inclusive, so the taxable
-- value is worked back out of the total and the tax is split equally between CGST and SGST for a
-- sale inside Karnataka, or shown as IGST for a sale outside it. This is the default format; a CA
-- can change the rates in one place.
CREATE TABLE IF NOT EXISTS invoices (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER UNIQUE NOT NULL REFERENCES orders(id),
    number TEXT UNIQUE NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    taxable_paise INTEGER NOT NULL,
    cgst_paise INTEGER NOT NULL DEFAULT 0,
    sgst_paise INTEGER NOT NULL DEFAULT 0,
    igst_paise INTEGER NOT NULL DEFAULT 0,
    total_paise INTEGER NOT NULL,
    place_of_supply TEXT,
    seller_gstin TEXT
);
