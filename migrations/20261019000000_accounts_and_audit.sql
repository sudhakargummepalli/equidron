-- Phase 1: real accounts, staff permissions, agent accounts and an audit trail. Safe to run again.
-- Also in SCHEMA in src/db.js; tests/postgres.test.js checks they match.
CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type TEXT NOT NULL CHECK (actor_type IN ('user', 'agent', 'system')),
    actor_id TEXT NOT NULL,
    run_id BIGINT,
    action TEXT NOT NULL,
    entity TEXT NOT NULL,
    entity_id TEXT NOT NULL,
    before JSONB,
    after JSONB,
    at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_log_entity ON audit_log (entity, entity_id);
CREATE TABLE IF NOT EXISTS login_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    ok INTEGER NOT NULL,
    at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS login_attempts_email ON login_attempts (email, at);
CREATE TABLE IF NOT EXISTS auth_codes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    purpose TEXT NOT NULL CHECK (purpose IN ('verify_email', 'reset_password')),
    code_hash TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    expires_at DOUBLE PRECISION NOT NULL,
    used_at DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS outbox (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id),
    channel TEXT NOT NULL,
    to_address TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    at TEXT NOT NULL
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS pw_algo TEXT NOT NULL DEFAULT 'pbkdf2:120000';
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified INTEGER NOT NULL DEFAULT 1;
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_secret TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_enabled INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS totp_last_step BIGINT;
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS decided_by INTEGER REFERENCES users(id);
ALTER TABLE returns ADD COLUMN IF NOT EXISTS decided_by INTEGER REFERENCES users(id);
-- Staff permissions, as a JSON list. Staff who existed before this change keep full access (admin).
-- Agent accounts get their own role, which no sign-in page accepts.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'users' AND column_name = 'permissions') THEN
        ALTER TABLE users ADD COLUMN permissions TEXT NOT NULL DEFAULT '[]';
        UPDATE users SET permissions = '["admin"]' WHERE role = 'ops';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'users_role_check' AND pg_get_constraintdef(oid) LIKE '%agent%') THEN
        ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
        ALTER TABLE users ADD CONSTRAINT users_role_check CHECK (role IN ('customer', 'seller', 'ops', 'agent'));
    END IF;
END $$;
