-- Phase 6: the marketplace's own rules, as versioned documents. Agents read the active version of
-- each kind and name it in their decisions; a person changes the policy, not the prompt.
CREATE TABLE IF NOT EXISTS policies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('returns', 'refunds', 'delivery', 'fees')),
    version INTEGER NOT NULL,
    body TEXT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (kind, version)
);
CREATE UNIQUE INDEX IF NOT EXISTS policies_one_active ON policies (kind) WHERE active;
