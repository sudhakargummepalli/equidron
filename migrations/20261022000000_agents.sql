-- Phase 4: the agent platform. An agent is its own user account (role 'agent') plus a row
-- here with its switch, autonomy level, model and daily budget. agent_runs and agent_steps
-- are the trace (every model call and tool call, personal data masked), approvals is the
-- inbox for actions that need a person, and eval_cases/eval_results are its test set.
CREATE TABLE IF NOT EXISTS agents (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    user_id INTEGER NOT NULL REFERENCES users(id),
    model TEXT NOT NULL,
    effort TEXT NOT NULL DEFAULT 'low',
    autonomy_level INTEGER NOT NULL DEFAULT 1 CHECK (autonomy_level BETWEEN 0 AND 4),
    enabled BOOLEAN NOT NULL DEFAULT false,
    max_steps INTEGER NOT NULL DEFAULT 8,
    daily_budget_usd NUMERIC(8, 2) NOT NULL DEFAULT 2.00
);
CREATE TABLE IF NOT EXISTS agent_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id TEXT NOT NULL REFERENCES agents(id),
    job_id BIGINT,
    trigger TEXT NOT NULL,
    subject TEXT,
    status TEXT NOT NULL CHECK (status IN ('running', 'done', 'waiting', 'failed', 'stopped')),
    input_tokens INTEGER NOT NULL DEFAULT 0,
    output_tokens INTEGER NOT NULL DEFAULT 0,
    cost_usd NUMERIC(10, 5) NOT NULL DEFAULT 0,
    summary TEXT,
    error TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS agent_runs_recent ON agent_runs (agent_id, started_at DESC);
CREATE INDEX IF NOT EXISTS agent_runs_open ON agent_runs (status) WHERE status IN ('running', 'waiting');
CREATE TABLE IF NOT EXISTS agent_steps (
    run_id BIGINT NOT NULL REFERENCES agent_runs(id),
    step INTEGER NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('model', 'tool')),
    tool TEXT,
    input JSONB,
    output JSONB,
    decision TEXT CHECK (decision IN ('execute', 'shadow', 'needs_approval', 'deny')),
    at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, step)
);
CREATE TABLE IF NOT EXISTS approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT REFERENCES agent_runs(id),
    agent_id TEXT NOT NULL REFERENCES agents(id),
    tool TEXT NOT NULL,
    payload JSONB NOT NULL,
    risk TEXT NOT NULL CHECK (risk IN ('read', 'write', 'money', 'irreversible')),
    amount_paise INTEGER,
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'expired')),
    decided_by INTEGER REFERENCES users(id),
    decided_at TIMESTAMPTZ,
    note TEXT,
    idempotency_key TEXT UNIQUE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS approvals_inbox ON approvals (status, created_at) WHERE status = 'pending';
CREATE TABLE IF NOT EXISTS eval_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id TEXT NOT NULL REFERENCES agents(id),
    name TEXT NOT NULL,
    fixture JSONB NOT NULL,
    expected JSONB NOT NULL,
    tags TEXT[] NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS eval_results (
    case_id BIGINT NOT NULL REFERENCES eval_cases(id),
    run_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    model TEXT NOT NULL,
    passed BOOLEAN NOT NULL,
    actual JSONB,
    cost_usd NUMERIC(10, 5)
);
