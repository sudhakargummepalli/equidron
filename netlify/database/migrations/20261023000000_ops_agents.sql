-- Phase 5: room for the first Ops agents. A submission keeps the Listing Review agent's
-- verdict next to the person's, which is what the agreement score is computed from, and
-- ops_tasks is the open work item Fulfilment Watch raises when a shipment is twice as late.
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS agent_run_id BIGINT;
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS agent_decision JSONB;
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS agent_confidence NUMERIC(4, 3);
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS agent_decided_at TIMESTAMPTZ;
CREATE TABLE IF NOT EXISTS ops_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'done')),
    dedupe_key TEXT UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    closed_by INTEGER REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS ops_tasks_open ON ops_tasks (status, created_at) WHERE status = 'open';
