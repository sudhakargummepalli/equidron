-- Phase 11: a seller's application, step by step. It is its own table until it is submitted, so a
-- half-finished form never becomes a seller. On submission a seller row and a dispatch warehouse are
-- created and Ops gets a task. No Aadhaar number is asked for or stored anywhere.
CREATE TABLE IF NOT EXISTS seller_applications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER UNIQUE NOT NULL REFERENCES users(id),
    business_name TEXT,
    business_type TEXT CHECK (business_type IN ('individual', 'proprietorship', 'partnership', 'private_limited')),
    pan TEXT,
    gstin TEXT,
    bank_account_name TEXT,
    bank_account_no TEXT,
    bank_ifsc TEXT,
    pickup_line1 TEXT,
    pickup_city TEXT,
    pickup_pincode TEXT,
    pickup_phone TEXT,
    agreement_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'approved', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at TIMESTAMPTZ
);
