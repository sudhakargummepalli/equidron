-- Phase 12: a payout is a batch a person approves, never an action a route takes on its own. The
-- lines hold what was due, the tax drafted on it, and the net; approving the batch is what moves
-- the money in the seller ledger.
CREATE TABLE IF NOT EXISTS payout_batches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    total_paise INTEGER NOT NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_by INTEGER REFERENCES users(id),
    decided_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS payout_lines (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id INTEGER NOT NULL REFERENCES payout_batches(id),
    seller_id INTEGER NOT NULL REFERENCES sellers(id),
    gross_paise INTEGER NOT NULL,
    tcs_paise INTEGER NOT NULL DEFAULT 0,
    tds_paise INTEGER NOT NULL DEFAULT 0,
    net_paise INTEGER NOT NULL,
    UNIQUE (batch_id, seller_id)
);
