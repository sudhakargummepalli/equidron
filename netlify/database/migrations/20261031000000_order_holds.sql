-- Phase 12: a hold is a record, not a flag on the order. It says who held it, why, and what the
-- risk score was at that moment; releasing it keeps the row, so the history survives.
CREATE TABLE IF NOT EXISTS order_holds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(id),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'released')),
    reason TEXT NOT NULL,
    score INTEGER NOT NULL,
    signals JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_by INTEGER REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    released_by INTEGER REFERENCES users(id),
    released_at TIMESTAMPTZ,
    release_note TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS order_holds_one_active ON order_holds (order_id) WHERE status = 'active';
