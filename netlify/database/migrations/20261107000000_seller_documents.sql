-- Phase 11: the documents a seller submits. Only a link is stored, never the file itself: an
-- https address the reviewer can open, with the query string stripped of tokens before display.
CREATE TABLE IF NOT EXISTS seller_documents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id INTEGER NOT NULL REFERENCES seller_applications(id),
    kind TEXT NOT NULL CHECK (kind IN ('pan_card', 'gst_certificate', 'bank_proof', 'cheque', 'other')),
    url TEXT NOT NULL,
    note TEXT,
    status TEXT NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'accepted', 'rejected')),
    reviewed_by INTEGER REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (application_id, kind)
);
