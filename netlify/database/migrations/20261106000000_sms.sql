-- Phase 10: SMS. India requires every business SMS to carry a registered DLT template id, so the
-- template is a column, not an afterthought. An opt-out is honoured for good.
ALTER TABLE users ADD COLUMN IF NOT EXISTS sms_opt_out_at TIMESTAMPTZ;
CREATE TABLE IF NOT EXISTS sms_messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id),
    phone TEXT NOT NULL,
    body TEXT NOT NULL,
    template_id TEXT,
    status TEXT NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'sent', 'failed')),
    provider_ref TEXT,
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS sms_messages_phone ON sms_messages (phone, created_at DESC);
