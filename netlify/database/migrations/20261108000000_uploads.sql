-- Phase 11: an uploaded file. The bytes live in a blob (disk locally, a bucket in production) and
-- the row holds only what a reviewer needs: name, type, size, hash, and who sent it.
CREATE TABLE IF NOT EXISTS uploads (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id),
    kind TEXT NOT NULL,
    filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    bytes INTEGER NOT NULL,
    sha256 TEXT NOT NULL,
    storage_key TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE seller_documents ADD COLUMN IF NOT EXISTS upload_id INTEGER REFERENCES uploads(id);
